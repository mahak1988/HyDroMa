// One-off generator: turns the legacy inline SVG sprite (app/src/index.html)
// into typed React icons in packages/icons. Idempotent; safe to re-run.
import { readFile, writeFile, mkdir } from "node:fs/promises";
import path from "node:path";

const ROOT = path.resolve(import.meta.dirname, "..");
const SOURCE = path.join(ROOT, "archive", "legacy-site", "src", "index.html");
const OUT_DIR = path.join(ROOT, "packages", "icons", "src");

const html = await readFile(SOURCE, "utf8");

const symbolRe = /<symbol\s+id="i-([a-z0-9-]+)"([^>]*)>([\s\S]*?)<\/symbol>/g;
const elementRe = /<(path|circle|rect|line|polyline|polygon)\b([^>]*?)\/>/g;

const icons = [];
let match;
while ((match = symbolRe.exec(html)) !== null) {
  const [, name, attrs, body] = match;
  const viewBox = /viewBox="([^"]+)"/.exec(attrs)?.[1] ?? "0 0 24 24";
  const elements = [];
  let el;
  while ((el = elementRe.exec(body)) !== null) {
    const [, tag, rawAttrs] = el;
    elements.push(`<${tag}${rawAttrs} />`);
  }
  if (elements.length === 0) continue;
  icons.push({ name, viewBox, elements });
}

if (icons.length === 0) throw new Error("no symbols found — has the legacy sprite moved?");

const names = icons.map((icon) => `"${icon.name}"`).join(", ");
const entries = icons
  .map(
    (icon) =>
      `  "${icon.name}": {\n    viewBox: "${icon.viewBox}",\n    body: (\n      <>\n        ${icon.elements.join("\n        ")}\n      </>\n    ),\n  },`,
  )
  .join("\n");

const file = `/**
 * Eco Nojin domain icons — 30 hand-drawn glyphs for water, soil, climate,
 * vegetation, MRV, landscape and tourism concepts that generic icon sets do not
 * cover (catchment, groundwater, deep percolation, nomadic territory, …).
 *
 * GENERATED FILE. Source: app/src/index.html (legacy sprite), regenerated by
 * scripts/extract-icons.mjs. Do not edit by hand.
 *
 * Every icon inherits \`currentColor\`, is stroked (never filled) and is
 * decorative by default — pass \`title\` when the icon carries meaning on its own.
 */
import type { ReactNode, SVGProps } from "react";

export const ICON_NAMES = [${names}] as const;

export type IconName = (typeof ICON_NAMES)[number];

type IconDefinition = { viewBox: string; body: ReactNode };

const DEFINITIONS: Record<IconName, IconDefinition> = {
${entries}
};

export type IconProps = Omit<SVGProps<SVGSVGElement>, "name"> & {
  name: IconName;
  /** Rendered width/height in px. */
  size?: number;
  /** Accessible name; omit for decorative icons. */
  title?: string;
};

export function Icon({ name, size = 20, title, ...rest }: IconProps) {
  const definition = DEFINITIONS[name];
  return (
    <svg
      viewBox={definition.viewBox}
      width={size}
      height={size}
      fill="none"
      stroke="currentColor"
      strokeWidth={1.6}
      strokeLinecap="round"
      strokeLinejoin="round"
      role={title ? "img" : undefined}
      aria-hidden={title ? undefined : true}
      focusable="false"
      {...rest}
    >
      {title ? <title>{title}</title> : null}
      {definition.body}
    </svg>
  );
}

export const iconNames = (): IconName[] => [...ICON_NAMES];
`;

const index = `export { Icon, ICON_NAMES, iconNames } from "./icons";
export type { IconName, IconProps } from "./icons";
`;

await mkdir(OUT_DIR, { recursive: true });
await writeFile(path.join(OUT_DIR, "icons.tsx"), file, "utf8");
await writeFile(path.join(OUT_DIR, "index.ts"), index, "utf8");
console.log(`icons: ${icons.length} → ${path.relative(ROOT, OUT_DIR)}`);