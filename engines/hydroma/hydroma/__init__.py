"""HyDroMA scientific runtime - Phase 2.1 MVP.

This package is the independent Python scientific engine. It owns no business
data and exposes only an HTTP/CLI contract. The TypeScript contract in
packages/scientific is the behavioural reference; this package reproduces the
Water Balance model faithfully and adds a persistent job lifecycle plus
provenance. Maturity stays ``tested`` - green unit tests are not scientific
validation, and the scientific status stays ``NOT_VALIDATED``.
"""

