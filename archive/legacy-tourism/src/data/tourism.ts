/** Demo quote: nights × room price, no taxes or fees. */
export function quoteStay(stay: Stay, startDate: string, endDate: string, guests: number): BookingQuote {
  const nights = Math.max(0, Math.round((Date.parse(endDate) - Date.parse(startDate)) / 86_400_000));
  const perNight = stay.price;
  return {
    amountMinor: perNight.amountMinor * nights,
    currency: perNight.currency,
    nights,
    guests,
    breakdown: [{ label: `${nights} × ${perNight.amountMinor} ${perNight.currency}`, amountMinor: perNight.amountMinor * nights }],
  };
}

export function quoteExperience(experience: Experience, guests: number): BookingQuote {
  return {
    amountMinor: experience.price.amountMinor * guests,
    currency: experience.price.currency,
    nights: 0,
    guests,
    breakdown: [{ label: `${guests} × ${experience.price.amountMinor} ${experience.price.currency}`, amountMinor: experience.price.amountMinor * guests }],
  };
}