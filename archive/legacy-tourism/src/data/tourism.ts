/** Localized text helper: English source first, then fa and ar. */
const L = (en: string, fa: string, ar: string): LocalizedText => ({ en, fa, ar });

/** ISO date helpers (UTC only; display calendars are a presentation concern). */
export const iso = (value: Date): string => value.toISOString().slice(0, 10);
const addDays = (base: string, days: number): string => {
  const date = new Date(`${base}T00:00:00.000Z`);
  date.setUTCDate(date.getUTCDate() + days);
  return iso(date);
};

/** Deterministic demo availability calendar starting 2026-06-01. */
function makeCalendar(total: number, seed: number, days = 21): AvailabilityDay[] {
  const start = "2026-06-01";
  return Array.from({ length: days }, (_, index) => {
    const booked = (index * 7 + seed * 3) % (total + 1);
    return { date: addDays(start, index), total, booked };
  });
}

